// 載入題目
function loadQuestion() {
    const currentQ = selectedQuestions[currentQuestionIndex];
    currentQNum.textContent = currentQuestionIndex + 1;
    questionText.textContent = `Q: ${currentQ.q}`;
    
    optionsContainer.innerHTML = '';
    const shuffledOptions = shuffleArray(currentQ.options);
    
    shuffledOptions.forEach(option => {
        const btn = document.createElement('button');
        btn.classList.add('btn', 'option-btn');
        btn.textContent = option;
        btn.addEventListener('click', () => selectOption(btn, option, currentQ));
        optionsContainer.appendChild(btn);
    });

    nextBtn.classList.add('hidden');
    submitBtn.classList.add('hidden');
}

// 處理選項點擊
function selectOption(selectedBtn, selectedText, currentQ) {
    const allOptions = optionsContainer.querySelectorAll('.option-btn');
    allOptions.forEach(btn => btn.disabled = true);

    if (selectedText === currentQ.answer) {
        selectedBtn.classList.add('correct');
        score += 5; // 每題 5 分 (共 20 題，滿分 100)
    } else {
        selectedBtn.classList.add('wrong');
        allOptions.forEach(btn => {
            if (btn.textContent === currentQ.answer) {
                btn.classList.add('correct');
            }
        });
        // 記錄錯題與解析
        wrongAnswers.push({
            question: currentQ.q,
            userChoice: selectedText,
            correctAnswer: currentQ.answer,
            explanation: currentQ.explanation
        });
    }

    if (currentQuestionIndex < selectedQuestions.length - 1) {
        nextBtn.classList.remove('hidden');
    } else {
        submitBtn.classList.remove('hidden');
    }
}

