// 發送資料至 Google Sheets (透過 fetch no-cors 模式避免跨域阻攔)
function syncDataToSpreadsheet(payload) {
    if (!GOOGLE_SCRIPT_URL) {
        syncStatus.textContent = "（尚未設定試算表串接網址，紀錄未連線）";
        syncStatus.style.color = "#706B66";
        return;
    }

    syncStatus.textContent = "試煉成績登記中...";
    syncStatus.style.color = "var(--ancient-brown)";

    fetch(GOOGLE_SCRIPT_URL, {
        method: "POST",
        mode: "no-cors",
        headers: {
            "Content-Type": "application/json"
        },
        body: JSON.stringify(payload)
    })
    .then(() => {
        syncStatus.textContent = `✦ 成績已成功登記於書齋名冊（第 ${payload.attemptCount} 次試煉）✦`;
        syncStatus.style.color = "var(--secondary-color)";
    })
    .catch((err) => {
        console.error("同步失敗:", err);
        syncStatus.textContent = "（成績登記失敗，請檢查網路連線）";
        syncStatus.style.color = "var(--primary-color)";
    });
}

